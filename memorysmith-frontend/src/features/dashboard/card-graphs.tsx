/** A stable choice among the drawings, from every character of the id. */
export function graphIndexOf(notebookId: string): number {
  // FNV-1a, 32 bits: small, stable across browsers, and spreads close ids.
  let hash = 0x811c9dc5;
  for (let at = 0; at < notebookId.length; at += 1) {
    hash ^= notebookId.charCodeAt(at);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash % GRAPHS.length;
}

const FILL: Record<Kind, string> = {
  b: 'var(--accent)',
  g: 'var(--node-green)',
  o: 'var(--signal)',
};

export function CardGraphDrawing({ notebookId }: { notebookId: string }) {
  const graph = GRAPHS[graphIndexOf(notebookId)] as CardGraph;
  return (
    <svg className="card-graph" viewBox="0 0 120 40" aria-hidden="true" focusable="false">
      <g stroke="var(--box-edge)" strokeWidth="1">
        {graph.edges.map(([x1, y1, x2, y2], at) => (
          <line key={at} x1={x1} y1={y1} x2={x2} y2={y2} />
        ))}
      </g>
      {graph.nodes.map(([cx, cy, r, kind], at) => (
        <circle key={at} cx={cx} cy={cy} r={r} fill={FILL[kind]} />
      ))}
    </svg>
  );
}
